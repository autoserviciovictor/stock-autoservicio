const fs = require('fs');
const assert = require('assert');
const proceso = fs.readFileSync('catalogo-imagenes-proceso.js','utf8');
const db = fs.readFileSync('db-catalogo-publico.js','utf8');
const server = fs.readFileSync('server.js','utf8');
const admin = fs.readFileSync('catalogo-admin.js','utf8');
const html = fs.readFileSync('index.html','utf8');
assert(db.includes('catalog_image_batch_state'), 'falta estado persistente del proceso masivo');
assert(db.includes("status TEXT NOT NULL DEFAULT 'idle'"), 'falta estado del job');
assert(db.includes('listarPendientesProcesoImagenesDb'), 'falta cola reanudable');
assert(proceso.includes('TAMANO_TANDA = 8') && proceso.includes('CONCURRENCIA = 2'), 'faltan límites de lote/concurrencia');
assert(proceso.includes('reanudarProcesoPendienteAlIniciar'), 'el job no se reanuda tras redeploy');
assert(server.includes('/admin/catalogo/imagenes/proceso/iniciar'), 'falta endpoint iniciar/reanudar');
assert(server.includes('/admin/catalogo/imagenes/proceso/pausar'), 'falta endpoint pausar');
assert(server.includes('/admin/catalogo/imagenes/proceso"'), 'falta endpoint de estado');
assert(admin.includes('cargarProcesoImagenes') && admin.includes('pausarImagenes'), 'falta control del proceso en admin');
assert(html.includes('catalogImagenesProcesoBarra') && html.includes('Completar imágenes automáticamente'), 'falta progreso en interfaz');
assert(!server.includes('/admin/catalogo/imagenes/buscar-lote'), 'quedó endpoint de lote viejo que compite con el proceso nuevo');
console.log('OK P4 proceso masivo: persistencia, pausa/reanudación y progreso verificados');
